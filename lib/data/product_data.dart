  static List<Product> getProductsByCategory(String category) {
    final searchCat = category.trim().toLowerCase();
    if (searchCat == 'all' || searchCat == 'all products' || searchCat.isEmpty) {
      return List.from(allProducts);
    }
    if (searchCat == 'general' || searchCat == 'general products') {
      return allProducts.where((p) => p.category == 'general').toList();
    }
    if (searchCat == 'orthopedic' || searchCat == 'ortho care' || searchCat == 'ortho') {
      return allProducts.where((p) => p.category == 'orthopedic').toList();
    }
    if (searchCat == 'gastroenterology' ||
        searchCat == 'gastrology' ||
        searchCat == 'gastro care' ||
        searchCat == 'gastro') {
      return allProducts.where((p) => p.category == 'gastroenterology').toList();
    }
    if (searchCat == 'neurology' || searchCat == 'neuro care' || searchCat == 'neuro') {
      return allProducts.where((p) => p.category == 'neurology').toList();
    }
    if (searchCat == 'gynecology' ||
        searchCat == 'gynacology' ||
        searchCat == 'obstetrics & gynaecology' ||
        searchCat == 'gynaec') {
      return allProducts.where((p) => p.category == 'gynecology').toList();
    }
    if (searchCat == 'cardiology' || searchCat == 'gardiology' || searchCat == 'hematology') {
      return allProducts
          .where((p) => p.category == 'general' || p.category == 'gastroenterology')
          .toList();
    }
    return allProducts.where((p) => p.category.toLowerCase() == searchCat).toList();
  }
